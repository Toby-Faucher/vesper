#!/usr/bin/env python3
"""Generate research/CATALOG.md from experiments/*/ (hypothesis.md, trace.md, result.json)."""
import argparse
import json
import os
import tempfile
from pathlib import Path

ORDER = ["accepted", "inconclusive", "rejected", "broken", "pending"]
HEADER = "| id | hypothesis | status | OVRL | SIG | BAK | SI-SDRi dB | RTF | n | branch | sha | note |"


def _lines(path):
    try:
        return path.read_text(encoding="utf-8").splitlines()
    except (OSError, ValueError):
        return []


def _title(path):
    for line in _lines(path):
        if line.startswith("# "):
            return line[2:].strip()
    return ""


def _first_line_under(path, heading):
    capturing = False
    for line in _lines(path):
        if line.startswith("## "):
            capturing = line[3:].strip().lower() == heading.lower()
        elif capturing and line.strip():
            return line.strip()
    return ""


def _delta(res, metric, digits):
    d = (res.get("deltas") or {}).get(metric)
    try:
        lo, hi = d["ci95"]
        return f"{d['mean']:+.{digits}f} [{lo:+.{digits}f}, {hi:+.{digits}f}]"
    except (TypeError, KeyError, ValueError):
        return ""


def _rtf(res):
    try:
        return f"{res['rtf']['cand']:.3f}"
    except (TypeError, KeyError, ValueError):
        return ""


def _cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def load(exp):
    path = exp / "result.json"
    res, unreadable = {}, False
    if path.exists():
        try:
            res = json.loads(path.read_text(encoding="utf-8"))
            if not isinstance(res, dict):
                raise ValueError("not an object")
        except (OSError, ValueError):
            res, unreadable = {}, True
    summary = _first_line_under(exp / "trace.md", "Summary")
    note = "unreadable result.json" if unreadable else "; ".join(
        x for x in (res.get("reason"), summary) if x)
    return {
        "id": exp.name,
        "title": _title(exp / "hypothesis.md"),
        "status": "broken" if unreadable else res.get("status", "pending"),
        "ovrl": _delta(res, "ovrl", 3),
        "sig": _delta(res, "sig", 3),
        "bak": _delta(res, "bak", 3),
        "sdr": _delta(res, "si_sdr_i", 2),
        "rtf": _rtf(res),
        "n": res.get("n_used", ""),
        "branch": f"exp/{exp.name}",
        "sha": str(res.get("cand_sha") or "")[:12],
        "note": note,
    }


def render(root):
    exps = root / "experiments"
    rows = [load(p) for p in sorted(exps.iterdir()) if p.is_dir()] if exps.is_dir() else []
    out = [
        "# Experiment catalog",
        "",
        "Generated by `research/scripts/catalog.sh`. Do not edit.",
        "Deltas are candidate minus baseline on the gate split, mean with a 95 percent interval,",
        "over the items the sequential test used (`n`). DNSMOS is a proxy: listen before you trust it.",
        "",
    ]
    if not rows:
        out += [HEADER, "|" + "---|" * 12, ""]
    for status in ORDER:
        group = [r for r in rows if r["status"] == status]
        if not group:
            continue
        out += [f"## {status.capitalize()} ({len(group)})", "", HEADER, "|" + "---|" * 12]
        for r in group:
            cells = [r[k] for k in ("id", "title", "status", "ovrl", "sig", "bak", "sdr", "rtf",
                                    "n", "branch", "sha", "note")]
            out.append("| " + " | ".join(_cell(c) for c in cells) + " |")
        out.append("")
    return "\n".join(out)


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    root = Path(p.parse_args(argv).root)
    text = render(root)
    fd, tmp = tempfile.mkstemp(dir=root, prefix=".CATALOG.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, root / "CATALOG.md")
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


if __name__ == "__main__":
    main()
